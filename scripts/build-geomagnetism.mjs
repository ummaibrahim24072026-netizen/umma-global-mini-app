// Reproducible, offline browser bundle of the pinned Apache-2.0 dependency.
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
import {dirname,relative} from 'node:path';
const resolve=createRequire(import.meta.url),entry=resolve.resolve('geomagnetism'),root=dirname(entry),modules=new Map();
function collect(path){
 const id=relative(root,path).replaceAll('\\','/');
 if(modules.has(id))return id;
 modules.set(id,'');
 let source=readFileSync(path,'utf8');
 if(path.endsWith('.json'))source='module.exports='+source+';';
 else source=source.replace(/require\(['"]([^'"]+)['"]\)/g,(_,ref)=>{
  if(!ref.startsWith('.'))throw Error('Unexpected external dependency: '+ref);
  return 'require('+JSON.stringify(collect(createRequire(path).resolve(ref)))+')';
 });
 modules.set(id,source);return id;
}
collect(entry);
const output='/* geomagnetism 0.2.0, Natural Atlas and contributors, Apache-2.0. See geomagnetism-LICENSE.txt. Generated by scripts/build-geomagnetism.mjs. */\n(()=>{const modules={'+[...modules].map(([id,body])=>JSON.stringify(id)+':function(module,exports,require){\n'+body+'\n}').join(',\n')+'};const cache={};function require(id){if(cache[id])return cache[id].exports;const module=cache[id]={exports:{}};modules[id](module,module.exports,require);return module.exports;}window.ummaGeomagnetism=require("index.js");})();\n';
writeFileSync('js/vendor/geomagnetism-0.2.0.js',output);
writeFileSync('js/vendor/geomagnetism-LICENSE.txt',readFileSync(root+'/LICENSE'));
