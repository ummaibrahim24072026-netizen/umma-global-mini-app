assert.equal(previewImport([{...row,purchase_price_vnd:NaN}])[0].action,'blocked');
assert.equal(previewImport([row],[{...row,variant_id:'variant'}])[0].variant_id,'variant');
assert.equal(previewImport([row],[{...row,variant_id:'a'},{...row,variant_id:'b'}])[0].action,'blocked');
const today='2026-10-17';
const media={source_type:'umma_original',source_ref:'original',permission_ref:'ownership',approved_by:'reviewer',commercial_use:true,sha256:'a'.repeat(64)};
const review={status:'verified_permissible',reviewer_id:'reviewer',reviewed_on:today,evidence_ref:'evidence'};
