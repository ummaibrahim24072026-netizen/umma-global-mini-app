assert.deepEqual(publicationBlockers(certified,media,{},today),[]);
assert(publicationBlockers(certified,media,{},'2026-10-18').includes('CERTIFICATE_INVALID_OR_EXPIRED'));
assert(publicationBlockers({...review,reviewed_on:'2026-10-18'},media,{permissible_without_certificate:true},today).includes('HALAL_REVIEW_INCOMPLETE'));
