assert(publicationBlockers(review,media,{},today).includes('CATEGORY_REQUIRES_CERTIFICATE'));
assert(publicationBlockers(review,null,{permissible_without_certificate:true},today).includes('MEDIA_RIGHTS_UNCONFIRMED'));
assert(publicationBlockers(review,media,{permissible_without_certificate:true,requires_slaughter_evidence:true},today).includes('SLAUGHTER_EVIDENCE_REQUIRED'));
assert(publicationBlockers(review,media,{permissible_without_certificate:true,requires_component_review:true},today).includes('COMPONENT_REVIEW_REQUIRED'));
