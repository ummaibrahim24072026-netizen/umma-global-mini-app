import assert from 'node:assert/strict';
import {validGTIN, previewImport, publicationBlockers} from '../js/market/catalog/import-preview.js';
assert.equal(validGTIN('4006381333931'), true);
assert.equal(validGTIN('96385074'), true);
assert.equal(validGTIN('4006381333932'), false);
assert.equal(validGTIN(4006381333931), false);
const row = {name_ru:'QA',name_en:'QA',name_vi:'QA',supplier_id:'supplier',supplier_sku:'001',gtin:'4006381333931',purchase_price_vnd:100,halal_status:'verified_certified',publication_status:'published'};
