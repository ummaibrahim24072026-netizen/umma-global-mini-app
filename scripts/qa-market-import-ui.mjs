import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {parseCSV} from '../js/market/catalog/csv.js';
const dom=new JSDOM('<div id="marketStatus"></div><div id="marketBody"></div>',{url:'https://example.test',runScripts:'outside-only'}),w=dom.window;
const calls=[];let jobs=[],id=0;
w.ummaI18n={locale:()=> 'ru'};
w.__csv={parseCSV};
w.ummaMarketApi={execute:async(action,data)=>{calls.push({action,data});if(action==='import_list')return {ok:true,jobs};if(action==='import_stage'){jobs=[{id:'job'+(++id),source_name:data.source_name,state:'staged',preview:data.rows.map((r,i)=>({row_number:i+1,name:r.name_ru,action:'create_draft',errors:[]}))}];return{ok:true};}if(action==='import_commit'){jobs[0].state='committed';jobs[0].result={processed:1};return{ok:true};}}};
w.eval(readFileSync('js/market/import.js','utf8').replace("await import('./catalog/csv.js')",'window.__csv'));
const tick=()=>new Promise(r=>setTimeout(r,10));
const render=roles=>w.document.dispatchEvent(new w.CustomEvent('umma:market-render',{detail:{tab:'import',warehouse:'wh',state:{roles,suppliers:[{id:'sup',name:'QA'}],categories:[{id:'cat',name_ru:'QA'}]}}}));
render(['cashier']);await tick();assert.match(w.document.getElementById('marketBody').textContent,/Нет доступа/);assert.equal(calls.length,0);
render(['admin']);await tick();
let form=w.document.querySelector('[data-import-form]');
const file={size:100,name:'qa.csv',text:async()=> 'name_ru,supplier_sku,gtin\n<script>alert(1)</script>,001,4006381333931'};
Object.defineProperty(form.elements.csv,'files',{value:[file]});
form.reportValidity=()=>true;
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
await tick();await tick();
assert.equal(calls.filter(c=>c.action==='import_stage').length,1);
assert.equal(calls.find(c=>c.action==='import_stage').data.rows[0].gtin,'4006381333931');
assert.equal(w.document.querySelectorAll('script').length,0);
const button=w.document.querySelector('[data-import-commit]');assert(button);button.click();button.click();await tick();
assert.equal(calls.filter(c=>c.action==='import_commit').length,1);
assert.match(w.document.getElementById('marketBody').textContent,/committed/);
assert.match(w.document.getElementById('marketStatus').textContent,/Импорт завершён/);
dom.window.close();
console.log('PASS import UI: admin-only workspace, CSV identifier preservation, escaped preview, explicit commit and duplicate-tap guard');
