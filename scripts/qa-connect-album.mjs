import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {connectMedia} from '../supabase/functions/cafe-connect/media.ts';

const {window:w}=new JSDOM('<form><textarea></textarea><button type="submit"></button><div id="status"></div></form>',{runScripts:'outside-only'});
w.Blob=Blob;
w.AbortSignal=AbortSignal;
w.File=File;
w.URL.createObjectURL=URL.createObjectURL;
w.URL.revokeObjectURL=URL.revokeObjectURL;
w.HTMLMediaElement.prototype.load=()=>{};
for(const name of ['connect-media','connect-composer'])w.eval(readFileSync('js/cafe/'+name+'.js','utf8'));
const form=w.document.querySelector('form'),body=form.querySelector('textarea');
const composer=w.ummaConnectComposer({lang:'ru',el:(tag,label,cls)=>{const n=w.document.createElement(tag);if(label)n.textContent=label;if(cls)n.className=cls;return n;},form,body,send:form.querySelector('button'),status:form.querySelector('#status'),onChange(){},compact:true,albums:true});
const jpeg=new File([Uint8Array.of(255,216,255,0)],'photo.jpg',{type:'image/jpeg'});
const mp4=new File([Uint8Array.of(0,0,0,8,102,116,121,112)],'video.mp4',{type:'video/mp4'});
const picker=form.querySelector('input[accept^="image/"][accept*="video/"]');
const attach=form.querySelector('.connect-attach');
const sheet=form.querySelector('.connect-attachment-sheet');
assert.equal(sheet.hidden,true);
attach.click();
assert.equal(sheet.hidden,false);
assert.equal(attach.getAttribute('aria-expanded'),'true');
const actions=[...sheet.querySelectorAll('.connect-attachment-action')];
assert.deepEqual(actions.map(action=>action.textContent),['Галерея','Камера','Видео']);
let galleryOpens=0;
picker.addEventListener('click',()=>galleryOpens++);
actions[0].click();
assert.equal(galleryOpens,1);
assert.equal(sheet.hidden,false);
form.querySelector('textarea').dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true}));
assert.equal(sheet.hidden,true);
attach.click();
sheet.querySelector('.connect-attachment-handle').click();
assert.equal(sheet.hidden,true);
assert.equal(w.document.activeElement,attach);
attach.click();
assert.equal(picker.multiple,true);
let files=[jpeg,mp4];
Object.defineProperty(picker,'files',{get:()=>files});
body.value='Подпись';
picker.dispatchEvent(new w.Event('change'));
assert.equal(form.querySelectorAll('.connect-draft-remove').length,2);
assert.equal(sheet.hidden,false);
form.querySelector('.connect-draft-remove').click();
assert.equal(composer.draft.kind,'video');
files=[jpeg];
picker.dispatchEvent(new w.Event('change'));
assert.equal(composer.draft.kind,'album');
const status=form.querySelector('#status');
files=Array(11).fill(jpeg);
picker.dispatchEvent(new w.Event('change'));
assert.match(status.textContent,/10 фото/);
assert.equal(composer.draft.items.length,2);

const api='https://example.invalid/connect';
let packed,calls=0;
w.fetch=async(url,init)=>{
 if(url!==api)return new Response(packed);
 calls++;
 const req=new Request(url,init);
 const parsed=await connectMedia(req,req.headers.get('content-type'));
 assert.equal(parsed.kind,'album');
 assert.equal(parsed.body,'Подпись');
 packed=parsed.bytes;
 return Response.json({ok:true,id:'message'});
};
await w.ummaConnectMedia.upload(api,{},composer.draft,'request',body.value,()=>{});
assert.equal(calls,1);
const restored=await w.ummaConnectMedia.albumFiles('https://example.invalid/media');
assert.deepEqual(Array.from(restored,file=>file.type),['video/mp4','image/jpeg']);
assert.deepEqual(new Uint8Array(await restored[1].arrayBuffer()),new Uint8Array(await jpeg.arrayBuffer()));
const album=w.ummaConnectMedia.inlineAlbum({album:'Фото и видео',photo:'Фото',video:'Видео',error:'Ошибка'},async()=> 'https://example.invalid/media');
w.document.body.append(album);
await album.querySelector('button').onclick();
assert.equal(album.querySelectorAll('img,video').length,2);
assert.equal(album.querySelector('button').hidden,true);
album.releaseAlbum();
composer.clear();
assert.equal(composer.draft,null);
assert.equal(body.value,'Подпись');

const invalid=new Blob(['""\n',JSON.stringify([{type:'image/jpeg',size:99},{type:'video/mp4',size:8}]),'\n',jpeg,mp4]);
await assert.rejects(connectMedia(new Request(api,{method:'POST',body:invalid}),'application/octet-stream'),/MEDIA_FORMAT/);
w.close();
console.log('Mixed album selection, removal, upload, validation and rendering passed');
